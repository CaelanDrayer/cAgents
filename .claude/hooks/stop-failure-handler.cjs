#!/usr/bin/env node
/**
 * Stop Failure Handler Hook - StopFailure event handler
 * cAgents V10.22.7
 *
 * Runs on StopFailure event to save recovery state and guide resumption.
 * Captures workflow state before the failed stop clears context.
 *
 * Input (stdin): JSON with error details from Claude Code
 * Output (stdout): JSON with continue:true and systemMessage about recovery location
 */

const fs = require('fs');
const path = require('path');
const {
  createHook,
  findActiveSession,
  extractYamlValue,
  safeRead,
  ensureDir,
  PROJECT_ROOT
} = require('./hook-utils.cjs');

function extractNestedController(content) {
  const match = content.match(/controller_assignment:\s*\n\s+primary:\s*["']?([^\s"'\n]+)/);
  return match ? match[1] : null;
}

createHook('StopFailureHandler', async (input) => {
  // Extract error details gracefully -- StopFailure input shape may vary
  const errorMessage = (input && (input.error || input.error_message || input.reason || '')) || '';
  const errorType = (input && (input.error_type || input.type || '')) || '';
  const sessionId = (input && input.session_id) || '';

  const sessionDir = findActiveSession(sessionId || undefined);
  if (!sessionDir) {
    // No active session -- nothing to save, just continue
    console.error('[StopFailureHandler] No active session found, skipping recovery state save');
    return null;
  }

  const sessionName = path.basename(sessionDir);
  const timestamp = new Date().toISOString();

  // Read current workflow state for recovery context
  const statusContent = safeRead(path.join(sessionDir, 'status.yaml'));
  const planContent = safeRead(path.join(sessionDir, 'workflow', 'plan.yaml'));
  const coordContent = safeRead(path.join(sessionDir, 'workflow', 'coordination_log.yaml'));

  const currentPhase = statusContent
    ? (extractYamlValue(statusContent, 'pipeline_state') ||
       extractYamlValue(statusContent, 'phase') ||
       extractYamlValue(statusContent, 'current_phase') ||
       'unknown')
    : 'unknown';

  const domain = planContent
    ? (extractYamlValue(planContent, 'domain') || extractYamlValue(planContent, 'super_domain') || 'unknown')
    : 'unknown';

  const controller = planContent
    ? (extractYamlValue(planContent, 'controller') ||
       extractYamlValue(planContent, 'primary_controller') ||
       extractNestedController(planContent) ||
       'unknown')
    : 'unknown';

  const coordStatus = coordContent
    ? (extractYamlValue(coordContent, 'status') || 'unknown')
    : 'not_started';

  // Count pending/in-progress work items for recovery context
  let pendingCount = 0;
  let inProgressCount = 0;
  if (coordContent) {
    const pendingMatches = coordContent.match(/status:\s*pending/g);
    const inProgressMatches = coordContent.match(/status:\s*in_progress/g);
    pendingCount = pendingMatches ? pendingMatches.length : 0;
    inProgressCount = inProgressMatches ? inProgressMatches.length : 0;
  }

  // Build recovery state YAML
  const recoveryStatePath = path.join(sessionDir, 'workflow', 'recovery_state.yaml');
  const recoveryContent = `# Recovery State
# Auto-generated by stop-failure-handler.cjs on StopFailure event
generated_at: "${timestamp}"
session_id: "${sessionName}"
event: stop_failure

failure:
  error_message: "${errorMessage.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n').slice(0, 500)}"
  error_type: "${errorType.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n')}"

workflow_state:
  phase: "${currentPhase}"
  domain: "${domain}"
  controller: "${controller}"
  coordination_status: "${coordStatus}"
  pending_work_items: ${pendingCount}
  in_progress_work_items: ${inProgressCount}

recovery:
  session_dir: "${path.relative(PROJECT_ROOT, sessionDir)}"
  status_file: "${path.relative(PROJECT_ROOT, path.join(sessionDir, 'status.yaml'))}"
  plan_file: "${path.relative(PROJECT_ROOT, path.join(sessionDir, 'workflow', 'plan.yaml'))}"
  coordination_log: "${path.relative(PROJECT_ROOT, path.join(sessionDir, 'workflow', 'coordination_log.yaml'))}"
  instructions: |
    To resume this session:
    1. Review the plan at workflow/plan.yaml
    2. Check coordination_log.yaml for completed/pending work items
    3. Re-run /run with the original request, or continue from the current phase
`;

  try {
    ensureDir(path.join(sessionDir, 'workflow'));
    fs.writeFileSync(recoveryStatePath, recoveryContent);
    console.error(`[StopFailureHandler] Recovery state saved to ${path.relative(PROJECT_ROOT, recoveryStatePath)}`);
  } catch (e) {
    console.error(`[StopFailureHandler] Failed to write recovery_state.yaml: ${e.message}`);
  }

  const recoveryRelPath = path.relative(PROJECT_ROOT, recoveryStatePath);
  const errorSummary = errorMessage ? ` Error: ${errorMessage.slice(0, 150)}` : '';

  return {
    continue: true,
    systemMessage: `[StopFailureHandler] Claude failed to stop cleanly.${errorSummary}\n\nWorkflow state (phase: ${currentPhase}, domain: ${domain}) saved to: ${recoveryRelPath}\n\nTo resume: review the recovery state file and re-run your original request, or check workflow/coordination_log.yaml for progress.`
  };
});
